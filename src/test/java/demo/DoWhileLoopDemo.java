package demo;

public class DoWhileLoopDemo {


    public static void main(String[] args) {


        // print number from 1 t0 10

        int i=1;


        while (i<=10){

            System.out.print(i);
            i++;


        }

        do {

            System.out.print(i);
            i++;

        }while (i<=20);


    }




}
